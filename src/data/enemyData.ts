import { Enemy } from '../types';

export function calculateEnemyHarvestCrystals(enemy: Enemy): number {
  if (enemy.rewards.minCrystals && enemy.rewards.maxCrystals) {
    const range = enemy.rewards.maxCrystals - enemy.rewards.minCrystals;
    return enemy.rewards.minCrystals + Math.floor(Math.random() * (range + 1));
  }
  return enemy.rewards.manaCrystals || 25;
}

